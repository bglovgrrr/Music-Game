// Copies the game rules (src/game/engine.ts + types.ts) into the room-action Edge Function,
// so the server applies exactly the same rules as the app. `--check` fails if they differ (CI).
import { mkdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs'

const OUT = 'supabase/functions/room-action/game'
const header = '// GENERATED by scripts/sync-edge.mjs from src/game. Do not edit here: edit src/game and run `npm run edge:sync`.\n'
const files = {
  'engine.ts': readFileSync('src/game/engine.ts', 'utf8').replace("from '@/lib/clock'", "from './clock.ts'").replace("from './types'", "from './types.ts'"),
  'types.ts': readFileSync('src/game/types.ts', 'utf8'),
  'clock.ts': "/** On the server, 'now' is simply the server's clock. */\nexport const clock = { now: () => Date.now() }\n",
}
const check = process.argv.includes('--check')
let stale = []
if (!check) mkdirSync(OUT, { recursive: true })
for (const [name, body] of Object.entries(files)) {
  const path = `${OUT}/${name}`
  const content = header + body
  if (check) {
    if (!existsSync(path) || readFileSync(path, 'utf8') !== content) stale.push(path)
  } else writeFileSync(path, content)
}
if (check && stale.length) {
  console.error(`Out of date (run npm run edge:sync): ${stale.join(', ')}`)
  process.exit(1)
}
console.log(check ? 'Edge function game rules are up to date.' : `Wrote ${Object.keys(files).length} files to ${OUT}`)
